import path from 'node:path';
import { readJSON, writeText, manifestPath, stateDir, readState } from './fs-utils.mjs';
import { SDK } from './deps.mjs';
import { readFindings, formatFindings } from './findings.mjs';

const li = (arr, empty = '(none)') => (arr && arr.length ? arr.map((x) => `- ${x}`).join('\n') : `- ${empty}`);

// Writes MIGRATION.md at the project root and a copy at .rn-new-arch/report.md.
export function writeReport(cwd) {
  const m = readJSON(manifestPath(cwd), {});
  const st = readState(cwd);
  const mig = st.migrate || {}, br = st.breaking || {}, gen = st.generate || {}, ver = st.verify || {};
  const fd = readFindings(cwd);
  const ai = st.ai || {}, q = st.quality || {};
  const manual = [...(m.manual || []), ...(mig.flags || []), ...(gen.manual || [])];
  if (br.todos) manual.push(`${br.todos} \`TODO(expo58)\` marker(s) in source need review (grep "TODO(expo58)")`);
  if (gen.extracted?.length) manual.push('Commit `.rn-new-arch/extracted-native/` (or move needed files into the repo) — the restore plugin reads from it on every prebuild/EAS build');
  const md = `# MIGRATION.md — ${m.packageJson?.name || 'app'} → Expo SDK 58

Generated by rn-new-arch-migrate on ${new Date().toISOString()}.

## Summary
- Project type before: ${m.projectType || 'unknown'}
- react-native ${m.versions?.reactNative ?? '?'} → ${SDK.reactNative}; react ${m.versions?.react ?? '?'} → ${SDK.react}; expo ${m.versions?.expo || '(none)'} → ${SDK.expo}
- Packages upgraded: ${mig.upgraded?.length || 0}; replaced: ${mig.replaced?.length || 0}; removed: ${mig.removed?.length || 0}
- Files changed by codemods: ${br.files?.length || 0}
- Native files extracted: ${gen.extracted?.length || 0}
- Manual items: ${manual.length}
- **Result: ${ver.verdict || 'not verified'}**

## Packages upgraded (npx expo install expo@${SDK.expo} → npx expo install --fix)
- Resolution: expo install expo@58 ${mig.resolution?.expo ? 'OK' : 'FAILED/not run'}, expo install --fix ${mig.resolution?.fix ? 'OK' : 'FAILED/not run'}, expo install --check ${mig.resolution?.check ? 'clean' : 'mismatches/not run'}
${li(mig.upgraded)}

Added:
${li(mig.added)}

## Packages replaced / removed
${li([...(mig.replaced || []).map((x) => `replaced ${x}`), ...(mig.removed || []).map((x) => `removed ${x}`)])}

## Breaking changes fixed
${li(br.files)}

## Native code extracted → config plugins
- prebuild --clean: ${gen.prebuild === undefined ? 'not run' : gen.prebuild ? 'OK' : 'FAILED'}
- Extracted to \`.rn-new-arch/extracted-native/\`:
${li(gen.extracted)}
- Re-applied by \`plugins/restore-native-overlay.js\`:
${li(gen.plugged)}

## Manual action list (could not automate)
${li(manual)}

## Quality & AI (profile: ${fd.profile || 'n/a'})
- Quality auto-fixes: ${q.done?.length ? q.done.join(', ') : 'not run'}
- AI: ${ai.provider ? `${ai.provider}, ${ai.batches} batch(es), applied ${ai.applied?.length || 0}, rejected ${ai.rejected?.length || 0}` : `not used${ai.reason ? ` (${ai.reason})` : ''}`}
${li(ai.applied)}

### Findings left for manual review (AI not run or not confident)
${li(ai.manual)}

### Manual-fixability findings
${li((fd.findings || []).filter((f) => f.fixability === 'manual').slice(0, 80).map((f) => `${f.file ? `${f.file}${f.line ? `:${f.line}` : ''} ` : ''}${f.tool}:${f.rule} — ${f.message}`))}
## Architecture & quality principles (leftovers)
Reusable components · single responsibility / separation of concerns · performance. Flagged by \`scan-quality\` heuristics (tool \`principles\`); fix in follow-up PRs or with the AI stage (\`--profile full\`).
${li((fd.findings || []).filter((f) => f.tool === 'principles' || ['scrollview-map', 'inline-style-object'].includes(f.rule)).slice(0, 80).map((f) => `[${f.category}/${f.fixability}] ${f.file || ''}${f.line ? `:${f.line}` : ''} ${f.rule} — ${f.message}${f.expectedGain ? ` _(gain: ${f.expectedGain})_` : ''}`), 'none detected')}

${formatFindings(fd).replace(/\n## /g, '\n### ')}
## Verification results
| Check | Status | Note |
|---|---|---|
${(ver.checks || []).map((c) => `| ${c.name} | ${c.status} | ${c.note || ''} |`).join('\n') || '| (verify not run) | | |'}

**${ver.verdict || 'NOT VERIFIED'}** — success is only declared once the app builds and launches on both iOS and Android (\`npx expo run:ios\` + \`npx expo run:android\`, or \`eas build -p all --profile development\`) with zero errors.
`;
  writeText(path.join(cwd, 'MIGRATION.md'), md);
  writeText(path.join(stateDir(cwd), 'report.md'), md);
  return md;
}

if (import.meta.url === `file://${process.argv[1]}`) writeReport(path.resolve(process.argv[2] || '.'));
